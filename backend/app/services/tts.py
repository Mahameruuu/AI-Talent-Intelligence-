"""Server-side text-to-speech for the AI interviewer (Gemini TTS), with a private on-disk cache.

Browsers often have no Indonesian voice (Safari, macOS without "Damayanti", most Linux), so the interviewer's
messages are synthesized here and played as audio. Audio is cached under ``TTS_CACHE_DIR`` (outside any
web-served directory) keyed by a hash of model, voice, language and text, and is pre-generated by the background
worker as soon as an interviewer message is created. Failures (rate limits, timeouts) raise :class:`TTSError`;
callers degrade to browser speech / captions.
"""

from __future__ import annotations

import base64
import hashlib
import json
import logging
import os
import re
import struct
import threading
import time
import urllib.error
import urllib.request
from pathlib import Path

from flask import current_app

from ..worker import worker

log = logging.getLogger(__name__)

API_URL = "https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
MAX_TEXT_CHARS = 2000
RATE_LIMIT_COOLDOWN_SECONDS = 45

# The voice/style comes from the prebuilt voice only. Tested against gemini-3.8-flash(-lite)-tts: any style
# instruction in the prompt ("Bacakan ...:", "Say warmly: ...", "[friendly] ...") is read aloud verbatim, and
# system instructions are rejected. Sending only the cleaned text is what reliably reads exactly the text.


class TTSError(Exception):
    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code  # disabled | rate_limited | timeout | provider_error | invalid_response


_locks: dict[str, threading.Lock] = {}
_locks_guard = threading.Lock()
_cooldown_until = 0.0


def _lock_for(key: str) -> threading.Lock:
    with _locks_guard:
        if len(_locks) > 500:
            _locks.clear()
        return _locks.setdefault(key, threading.Lock())


def enabled() -> bool:
    cfg = current_app.config
    return cfg.get("TTS_PROVIDER", "none") == "gemini" and bool(cfg.get("TTS_API_KEY"))


_EMOJI = re.compile("[\U0001F000-\U0001FAFF\U00002600-\U000027BF\U0001F1E6-\U0001F1FF️‍]")


def clean_text(text: str) -> str:
    """Remove markdown syntax and emojis so only speakable text is sent."""
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)  # [label](url) -> label
    text = re.sub(r"```.*?```", " ", text, flags=re.S)
    text = re.sub(r"^\s{0,3}(#{1,6}|>|[-*+]\s)\s*", "", text, flags=re.M)
    text = re.sub(r"[*_`~#]+", "", text)
    text = _EMOJI.sub("", text)
    return re.sub(r"\s+", " ", text).strip()[:MAX_TEXT_CHARS]


def _cache_dir() -> Path:
    root = Path(current_app.config["TTS_CACHE_DIR"])
    root.mkdir(parents=True, exist_ok=True, mode=0o700)
    return root


def cache_key(text: str, lang: str) -> str:
    cfg = current_app.config
    raw = f"{cfg['TTS_MODEL']}|{cfg['TTS_VOICE']}|{lang}|{clean_text(text)}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def _store(key: str, audio: bytes) -> None:
    path = _cache_dir() / f"{key}.wav"
    tmp = path.with_suffix(f".{os.getpid()}.{threading.get_ident()}.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as fh:
        fh.write(audio)
    os.replace(tmp, path)


def pcm_to_wav(pcm: bytes, rate: int = 24000, channels: int = 1, bits: int = 16) -> bytes:
    block = channels * bits // 8
    header = struct.pack("<4sI4s4sIHHIIHH4sI", b"RIFF", 36 + len(pcm), b"WAVE", b"fmt ", 16, 1, channels, rate,
                         rate * block, block, bits, b"data", len(pcm))
    return header + pcm


def _audio_from_response(payload: dict) -> bytes:
    try:
        parts = payload["candidates"][0]["content"]["parts"]
    except (KeyError, IndexError, TypeError) as exc:
        raise TTSError("invalid_response", "The TTS provider returned no audio.") from exc
    inline = next((p.get("inlineData") or p.get("inline_data") for p in parts
                   if isinstance(p, dict) and (p.get("inlineData") or p.get("inline_data"))), None)
    if not inline or not inline.get("data"):
        raise TTSError("invalid_response", "The TTS provider returned no audio.")
    try:
        data = base64.b64decode(inline["data"])
    except (ValueError, TypeError) as exc:
        raise TTSError("invalid_response", "The TTS provider returned malformed audio.") from exc
    mime = (inline.get("mimeType") or inline.get("mime_type") or "").lower()
    if data[:4] == b"RIFF" and data[8:12] == b"WAVE":
        return data
    if "l16" in mime or "pcm" in mime:
        match = re.search(r"rate=(\d+)", mime)
        return pcm_to_wav(data, rate=int(match.group(1)) if match else 24000)
    raise TTSError("invalid_response", f"Unsupported audio format from the TTS provider: {mime or 'unknown'}.")


def _post_json(url: str, body: dict, api_key: str, timeout: float) -> dict:
    """POST JSON and decode the JSON response (the key travels only in a header). Mocked in tests."""
    req = urllib.request.Request(url, data=json.dumps(body).encode("utf-8"), method="POST",
                                 headers={"Content-Type": "application/json", "x-goog-api-key": api_key})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as res:  # noqa: S310 (fixed https URL)
            return json.loads(res.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        if exc.code == 429:
            raise TTSError("rate_limited", "The TTS provider rate limit was reached.") from None
        raise TTSError("provider_error", f"The TTS provider answered HTTP {exc.code}.") from None
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        raise TTSError("timeout", f"The TTS provider could not be reached ({type(exc).__name__}).") from None
    except ValueError:
        raise TTSError("invalid_response", "The TTS provider returned invalid JSON.") from None


def _request(model: str, text: str) -> bytes:
    cfg = current_app.config
    body = {
        "contents": [{"parts": [{"text": text}]}],
        "generationConfig": {
            "responseModalities": ["AUDIO"],
            "speechConfig": {"voiceConfig": {"prebuiltVoiceConfig": {"voiceName": cfg["TTS_VOICE"]}}},
        },
    }
    payload = _post_json(API_URL.format(model=model), body, cfg["TTS_API_KEY"], float(cfg["TTS_TIMEOUT_SECONDS"]))
    return _audio_from_response(payload)


def synthesize(text: str, lang: str) -> bytes:
    """WAV audio for ``text`` (cached). Raises :class:`TTSError` when disabled or the provider fails."""
    global _cooldown_until
    if not enabled():
        raise TTSError("disabled", "Server text-to-speech is not configured.")
    lang = "id" if lang == "id" else "en"
    spoken = clean_text(text)
    if not spoken:
        raise TTSError("invalid_response", "Nothing to say.")
    key = cache_key(text, lang)
    with _lock_for(key):  # a request arriving while the worker synthesizes waits instead of calling twice
        path = _cache_dir() / f"{key}.wav"
        if path.is_file():
            return path.read_bytes()
        if time.monotonic() < _cooldown_until:
            raise TTSError("rate_limited", "The TTS provider rate limit was reached recently.")
        cfg = current_app.config
        models = [m for m in dict.fromkeys([cfg["TTS_MODEL"], cfg.get("TTS_FALLBACK_MODEL") or ""]) if m]
        last: TTSError | None = None
        for model in models:
            started = time.monotonic()
            try:
                audio = _request(model, spoken)
            except TTSError as exc:
                log.warning("TTS failed with model %s: %s (%s)", model, exc.code, exc)
                last = exc
                continue
            log.info("TTS synthesized %d chars with %s in %.1fs", len(spoken), model, time.monotonic() - started)
            _store(key, audio)
            return audio
        assert last is not None
        if last.code == "rate_limited":
            _cooldown_until = time.monotonic() + RATE_LIMIT_COOLDOWN_SECONDS
        raise last


def _pregenerate_job(message_id: int) -> None:
    from ..extensions import db
    from ..models import InterviewMessage
    from .interviews import session_language

    message = db.session.get(InterviewMessage, message_id)
    if message is None or message.role != "assistant":
        return
    try:
        synthesize(message.content, session_language(message.session))
    except TTSError as exc:
        log.info("TTS pre-generation skipped for message %s: %s", message_id, exc.code)


def _pregenerate_text_job(text: str, lang: str) -> None:
    try:
        synthesize(text, lang)
    except TTSError as exc:
        log.info("TTS pre-generation of an upcoming question skipped: %s", exc.code)


def pregenerate(message_ids: list[int], upcoming: list[tuple[str, str]] | None = None) -> None:
    """Queue synthesis of new interviewer messages so audio is ready when the candidate's browser asks.

    ``upcoming`` holds ``(text, lang)`` of the likely next interviewer message (cached by text, so it is a cache hit
    when the message is created with exactly that text).
    """
    if not enabled():
        return
    for message_id in message_ids:
        worker.submit(f"tts:{message_id}", _pregenerate_job, message_id)
    for text, lang in upcoming or []:
        worker.submit(f"tts-text:{cache_key(text, lang)}", _pregenerate_text_job, text, lang)
